"""The fixed shape of a generated skill: Claude fills in a typed spec, code checks it against the
rules below and renders SKILL.md from one template. The same spec always renders the same file.

Rules (each failure is reported by `validate`):
- Agent Skills standard (https://agentskills.io/specification): name is lowercase letters, digits,
  and single hyphens, at most 64 characters, equal to the folder name; the description is 1 to
  1024 characters and says when to use the skill ("Use when ...").
- Every step proves it is done (`done_check`) and cites at least one source post that exists.
- A step that publishes, sends, buys, deploys, deletes, or changes a live system requires approval
  (`repair` sets the flag on a step the rule flags, before validation counts it).
- Step ids are unique; a step that names a script names one the spec ships.
- Scripts are single Python files with inline dependencies (PEP 723, run with `uv run`), read
  only: no shell commands, file deletion, dynamic code, or outgoing writes (POST and friends).
"""

import re
from pathlib import Path

from pydantic import BaseModel, Field

NAME_PATTERN = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
SCRIPT_NAME_PATTERN = re.compile(r"^[a-z0-9_]+\.py$")
RISKY_WORDS = re.compile(
    r"\b(publish|deploy|send|email|post to|tweet|submit|purchase|buy|pay for|spend|delete|push|merge|"
    r"go live|upload|sign up|subscribe)\b",
    re.IGNORECASE,
)
FORBIDDEN_IN_SCRIPTS = {
    r"\bsubprocess\b": "runs shell commands",
    r"\bos\.system\b": "runs shell commands",
    r"\bos\.(remove|unlink|rmdir)\b|\bshutil\.rmtree\b|\.unlink\(": "deletes files",
    # A bare eval( or exec( call; a method such as JavaScript's regex.exec( inside an emitted string is not one.
    r"(?<![\w.])(eval|exec)\(|\bbuiltins\.(eval|exec)\b": "runs dynamic code",
    r"\.(post|put|patch|delete)\(": "sends writes to a server",
    r"\bsmtplib\b": "sends email",
}
MARKER = "Generated by Alpha"
DESCRIPTION_LIMIT = 1024


class Input(BaseModel):
    name: str
    why: str = Field(description="What the skill needs it for")
    required: bool
    fallback: str = Field(description="What to do without it (free alternative), or empty if none exists")


class Step(BaseModel):
    id: str = Field(description="Short lowercase-hyphen id, kept stable across versions")
    title: str
    action: str = Field(description="What the agent does, concretely")
    script: str = Field(description="Filename of a shipped script this step runs, or empty")
    tools: str = Field(description="Tools, services, or commands the posts name for this step, or empty")
    fallback: str = Field(description="Free alternative when a named tool or access is missing, and how much less to trust it; or empty")
    done_check: str = Field(description="Observable evidence that the step is complete")
    requires_approval: bool = Field(description="True when the step publishes, sends, spends, deletes, or changes a live system")
    sources: list[int] = Field(description="Numbers of the source posts that support this step")


class Script(BaseModel):
    filename: str = Field(description="snake_case name ending in .py")
    purpose: str
    usage: str = Field(description="Command line, e.g. uv run scripts/crawl_links.py https://example.com --max-pages 50")
    smoke_command: str = Field(
        description="Command for the build's test; {target} where the test task goes when the script takes that "
        "kind of input, otherwise a small fixed example input"
    )
    code: str = Field(description="Complete file starting with a PEP 723 `# /// script` block listing dependencies")


class SkillSpec(BaseModel):
    description: str = Field(description="What the skill does, then 'Use when ...' with the trigger phrases. At most 1024 characters.")
    purpose: str
    inputs: list[Input]
    steps: list[Step]
    checklist: list[str]
    pitfalls: list[str]
    output: list[str] = Field(description="Sections of the report the agent hands back; say which items are proposed vs done")
    scripts: list[Script]


def risky_word(step: Step) -> str | None:
    """The word that makes a step change something outside the agent, or None."""
    match = RISKY_WORDS.search(f"{step.title} {step.action}")
    return match and match.group(0).lower()


def fits(description: str) -> bool:
    return 1 <= len(description) <= DESCRIPTION_LIMIT and "use when" in description.lower()


def trim_description(description: str) -> str:
    """The description cut at sentence boundaries until it fits, keeping the first sentence and the 'Use when'
    one: sentences between them go first, then those after it, a 'Not for ...' routing sentence last (each
    group from the end). The description unchanged when no cut fits."""
    sentences = re.split(r"(?<=[.!?])\s+", " ".join(description.split()))
    trigger = next((i for i, sentence in enumerate(sentences) if "use when" in sentence.lower()), None)
    if trigger is None:
        return description
    after = range(len(sentences) - 1, trigger, -1)
    routing = [i for i in after if "not for" in sentences[i].lower()]
    order = [*range(trigger - 1, 0, -1), *(i for i in after if i not in routing), *routing]
    kept = set(range(len(sentences)))
    for index in order:
        if fits(" ".join(sentences[i] for i in sorted(kept))):
            break
        kept.discard(index)
    trimmed = " ".join(sentences[i] for i in sorted(kept))
    return trimmed if fits(trimmed) else description


def repair(spec: SkillSpec) -> list[str]:
    """Fix in place what needs no judgment, before validation counts it as a problem: a step the approval
    rule flags gets requires_approval. Returns one sentence per change."""
    repairs = []
    for step in spec.steps:
        if (word := risky_word(step)) and not step.requires_approval:
            step.requires_approval = True
            repairs.append(f"step {step.id} now requires approval (its action says '{word}')")
    return repairs


def validate(spec: SkillSpec, name: str, source_count: int) -> list[str]:
    errors = []
    if not NAME_PATTERN.match(name) or len(name) > 64:
        errors.append(f"name {name!r} breaks the Agent Skills naming rules")
    if not 1 <= len(spec.description) <= DESCRIPTION_LIMIT:
        errors.append(f"description is {len(spec.description)} characters; it must be 1 to {DESCRIPTION_LIMIT}")
    if "use when" not in spec.description.lower():
        errors.append("description does not say when to use the skill ('Use when ...')")
    if not spec.steps:
        errors.append("the skill has no steps")
    ids = [step.id for step in spec.steps]
    for duplicate in sorted({i for i in ids if ids.count(i) > 1}):
        errors.append(f"step id {duplicate!r} is used more than once")
    scripts = {script.filename for script in spec.scripts}
    for step in spec.steps:
        if not NAME_PATTERN.match(step.id):
            errors.append(f"step id {step.id!r} is not lowercase-with-hyphens")
        if not step.done_check.strip():
            errors.append(f"step {step.id} has no done check")
        if not step.sources:
            errors.append(f"step {step.id} cites no source post")
        if bad := [n for n in step.sources if not 1 <= n <= source_count]:
            errors.append(f"step {step.id} cites posts that do not exist: {bad}")
        if risky_word(step) and not step.requires_approval:
            errors.append(f"step {step.id} changes something outside the agent (publish, send, buy, delete...) but does not require approval")
        if step.script and step.script not in scripts:
            errors.append(f"step {step.id} runs {step.script}, which the skill does not ship")
    for script in spec.scripts:
        if not SCRIPT_NAME_PATTERN.match(script.filename):
            errors.append(f"script name {script.filename!r} must be snake_case .py")
        if "# /// script" not in script.code:
            errors.append(f"script {script.filename} has no PEP 723 '# /// script' dependency block")
        if not script.smoke_command.startswith(f"uv run scripts/{script.filename}"):
            errors.append(f"script {script.filename} smoke command must start with `uv run scripts/{script.filename}`")
        for pattern, reason in FORBIDDEN_IN_SCRIPTS.items():
            if re.search(pattern, script.code):
                errors.append(f"script {script.filename} {reason}; scripts must only read")
        if not any(step.script == script.filename for step in spec.steps):
            errors.append(f"script {script.filename} is not used by any step")
    return errors


def _bullets(items: list[str]) -> list[str]:
    return [f"- {item}" for item in items]


def _sentence(text: str) -> str:
    text = " ".join(text.split())
    return text if not text or text[-1] in ".!?:" else f"{text}."


def render(spec: SkillSpec, name: str, sources: list[tuple[str, str]], version: int, built_on: str) -> str:
    lines = [
        "---",
        f"name: {name}",
        f"description: {' '.join(spec.description.split())}",
        "---",
        f"<!-- {MARKER}: version {version}, {built_on}, from {len(sources)} saved posts. Edits here are overwritten. -->",
        "",
        f"# {name}",
        "",
        spec.purpose.strip(),
        "",
        "## Inputs",
        "",
        "Get these from the user first. If one is missing, use its fallback and say so in the report.",
        "",
    ]
    for item in spec.inputs:
        need = "required" if item.required else "optional"
        fallback = f" Without it: {_sentence(item.fallback)}" if item.fallback else ""
        lines.append(f"- **{item.name}** ({need}): {_sentence(item.why)}{fallback}")
    lines += [
        "",
        "## Modes",
        "",
        "- **Report only** (the default when the user does not say): do every step. For a step marked",
        "  *Needs approval*, do its read-only part and write the change as a proposal instead of making it.",
        "- **Apply**: also make the changes, asking the user before each step marked *Needs approval*.",
        "",
        "When no user is available to answer (an unattended or test run), work in report-only mode, make",
        "the choices the inputs ask for yourself, and state each choice and why in the report.",
        "",
        "If a step is blocked (missing access, a failing script, an unreachable site), record why, continue",
        "with the steps that do not depend on it, and still deliver every Output section, marking the ones",
        "that could not be done and why.",
        "",
        "## Procedure",
        "",
    ]
    for number, step in enumerate(spec.steps, 1):
        cited = "".join(f"[{n}]" for n in step.sources)
        approval = " *Needs approval.*" if step.requires_approval else ""
        lines.append(f"### {number}. {step.title} `{step.id}`{approval}")
        lines.append("")
        lines.append(f"{step.action.strip()} {cited}")
        if step.script:
            usage = next(s.usage for s in spec.scripts if s.filename == step.script)
            lines += ["", f"Run: `{usage}`"]
        if step.tools:
            lines += ["", f"Tools: {step.tools}"]
        if step.fallback:
            lines += ["", f"Fallback: {step.fallback}"]
        lines += ["", f"Done when: {step.done_check}", ""]
    lines += ["## Checklist", "", *[f"- [ ] {item}" for item in spec.checklist], ""]
    lines += ["## Pitfalls", "", *_bullets(spec.pitfalls), ""]
    lines += ["## Output", "", *[f"{n}. {item}" for n, item in enumerate(spec.output, 1)], ""]
    if spec.scripts:
        lines += ["## Scripts", "", "In `scripts/`, run from this skill's folder with `uv run` (dependencies install themselves):", ""]
        lines += [f"- `{s.filename}`: {s.purpose}" for s in spec.scripts]
        lines.append("")
    lines += ["## Sources", ""]
    lines += [f"{n}. {title}: {url}" for n, (title, url) in enumerate(sources, 1)]
    return "\n".join(lines) + "\n"


def write_files(directory: Path, skill_md: str, spec: SkillSpec) -> None:
    """Write SKILL.md and scripts/ into an empty or previously generated folder."""
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "SKILL.md").write_text(skill_md)
    scripts = directory / "scripts"
    if scripts.is_dir():
        for old in scripts.glob("*.py"):
            old.unlink()
    if spec.scripts:
        scripts.mkdir(exist_ok=True)
        for script in spec.scripts:
            (scripts / script.filename).write_text(script.code.rstrip() + "\n")


def cited(spec: SkillSpec) -> set[int]:
    """Numbers of the source posts at least one step cites."""
    return {number for step in spec.steps for number in step.sources}


def renumber(spec: SkillSpec, old: list[str], new: list[str]) -> SkillSpec:
    """The same spec citing posts by their place in `new` (post ids) instead of in `old`. Citations
    of posts not in `new` are dropped. Used to drop uncited posts from a version's sources, and to
    show the writer the live spec in the numbering of the posts it is given now."""
    position = {post_id: number for number, post_id in enumerate(new, 1)}
    spec = spec.model_copy(deep=True)
    for step in spec.steps:
        step.sources = [position[old[n - 1]] for n in step.sources if 1 <= n <= len(old) and old[n - 1] in position]
    return spec


def description_of(skill_md: str) -> str:
    """The description in a SKILL.md's YAML frontmatter, plain, quoted, or a folded (>-) or literal (|)
    block, on one line."""
    lines = skill_md.split("\n")
    if not lines or lines[0].strip() != "---":
        return ""
    for index, line in enumerate(lines[1:], 1):
        if line.strip() == "---":
            return ""
        if not line.startswith("description:"):
            continue
        parts = [line.removeprefix("description:").strip()]
        for following in lines[index + 1:]:
            if following.strip() == "---" or (following[:1] and not following[0].isspace()):
                break
            parts.append(following.strip())
        if parts[0][:1] in ("|", ">"):
            parts = parts[1:]
        value = " ".join(part for part in parts if part)
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        return value
    return ""
