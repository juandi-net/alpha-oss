"""Rebuild the vault pages from the database (optional: off when `output_directory` is unset). Pages carry
a `generated_by` marker; only marked files are replaced or removed, so notes written by hand are never touched."""

import sqlite3
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote

from .config import Settings
from .storage import RESOURCE_KINDS, now

MARKER = "generated_by: alpha"
INDEX_PAGE = "Alpha Index"
LIBRARY_PAGE = "All Items"


def _link_text(text: str | None) -> str:
    return (text or "Untitled").replace("[", "(").replace("]", ")").replace("\n", " ")


def page_link(name: str) -> str:
    """Relative link to a sibling page; unambiguous even when a vault note has the same name."""
    return f"[{name}]({quote(name)}.md)"


def _header(title: str) -> list[str]:
    return [
        "---",
        MARKER,
        f"updated: {now()}",
        "---",
        f"# {title}",
        "",
        "> Generated by Alpha. Edits here are overwritten; change the project spec instead.",
        "",
    ]


def duplicates_by_original(connection: sqlite3.Connection) -> dict[str, list[str]]:
    """Canonical item id -> later item ids that repeat its idea."""
    result: dict[str, list[str]] = defaultdict(list)
    for row in connection.execute("SELECT id, duplicate_of FROM items WHERE duplicate_of IS NOT NULL ORDER BY created_at"):
        result[row["duplicate_of"]].append(row["id"])
    return result


def _also_saved(connection: sqlite3.Connection, item_ids: list[str]) -> str | None:
    if not item_ids:
        return None
    urls = {
        row["id"]: row["url"]
        for row in connection.execute(f"SELECT id, url FROM items WHERE id IN ({','.join('?' * len(item_ids))})", item_ids)
    }
    return "- Same idea also saved: " + ", ".join(f"[item {n}]({urls[i]})" for n, i in enumerate(item_ids, 1) if i in urls)


def _ordered_categories(settings: Settings, present: set[str]) -> list[str]:
    return [name for name in settings.categories if name in present] + sorted(present - settings.categories.keys())


def _project_page(connection, settings, project: sqlite3.Row, duplicates) -> list[str]:
    rows = connection.execute(
        "SELECT i.*, r.score, r.reason FROM relevance r JOIN items i ON i.id = r.item_id "
        "WHERE r.project = ? AND r.score >= ? ORDER BY r.score DESC, i.created_at DESC",
        (project["name"], settings.relevance_threshold),
    ).fetchall()
    lines = _header(f"{project['name']}: related items")
    lines += [f"Spec source: `{project['source']}`", "", f"Related items: {len(rows)}", ""]
    # Datasets, models, and Spaces are resources for the project, listed apart from the ideas (they never feed skills).
    resources = "Resources (datasets, models, Spaces)"
    groups: dict[str, list[sqlite3.Row]] = defaultdict(list)
    for row in rows:
        groups[resources if row["kind"] in RESOURCE_KINDS else row["category"]].append(row)
    for group in [*_ordered_categories(settings, set(groups) - {resources}),
                  *([resources] if resources in groups else [])]:
        lines += [f"## {group} ({len(groups[group])})", ""]
        for row in groups[group]:
            lines.append(f"### [{_link_text(row['title'])}]({row['url']})")
            lines.append(f"- Relevance: {row['score']:.1f} of 3 · {row['source']} {row['kind']} · "
                         f"published {(row['created_at'] or '')[:10]}")
            lines.append(f"- Why: {row['reason'] or 'Reason not written yet; the next run writes it.'}")
            lines.append(f"- Summary: {row['summary']}")
            also = _also_saved(connection, duplicates.get(row["id"], []))
            if also:
                lines.append(also)
            lines.append("")
    return lines


def _library_page(connection, settings, duplicates) -> list[str]:
    rows = connection.execute(
        "SELECT * FROM items WHERE classified_at IS NOT NULL AND duplicate_of IS NULL ORDER BY created_at DESC"
    ).fetchall()
    matches: dict[str, list[str]] = defaultdict(list)
    for row in connection.execute(
        "SELECT item_id, project FROM relevance WHERE score >= ? ORDER BY project", (settings.relevance_threshold,)
    ):
        matches[row["item_id"]].append(row["project"])
    lines = _header(LIBRARY_PAGE)
    lines += [f"{len(rows)} distinct ideas. Repeats are listed under the first item of each idea.", ""]
    by_category: dict[str, list[sqlite3.Row]] = defaultdict(list)
    for row in rows:
        by_category[row["category"]].append(row)
    for category in _ordered_categories(settings, set(by_category)):
        lines += [f"## {category} ({len(by_category[category])})", ""]
        for row in by_category[category]:
            projects = ", ".join(page_link(name) for name in matches.get(row["id"], [])) or "none"
            lines.append(f"### [{_link_text(row['title'])}]({row['url']})")
            lines.append(f"- {row['summary']}")
            lines.append(f"- Projects: {projects}")
            also = _also_saved(connection, duplicates.get(row["id"], []))
            if also:
                lines.append(also)
            lines.append("")
    return lines


def _index_page(connection, settings) -> list[str]:
    counts = {
        row["name"]: row["matches"]
        for row in connection.execute(
            "SELECT p.name, COUNT(r.item_id) AS matches FROM projects p "
            "LEFT JOIN relevance r ON r.project = p.name AND r.score >= ? GROUP BY p.name ORDER BY p.name",
            (settings.relevance_threshold,),
        )
    }
    total = connection.execute("SELECT COUNT(*) FROM items").fetchone()[0]
    duplicates = connection.execute("SELECT COUNT(*) FROM items WHERE duplicate_of IS NOT NULL").fetchone()[0]
    lines = _header(INDEX_PAGE)
    lines += [f"{total} items, {duplicates} repeat an earlier idea. See {page_link(LIBRARY_PAGE)}.", ""]
    lines += ["| Project | Related items |", "| --- | --- |"]
    lines += [f"| {page_link(name)} | {count} |" for name, count in counts.items()]
    return lines


def _is_generated(path: Path) -> bool:
    with path.open(errors="replace") as handle:
        return MARKER in handle.read(200)


def render(connection: sqlite3.Connection, settings: Settings) -> None:
    directory = settings.output_directory
    if directory is None:
        return
    directory.mkdir(parents=True, exist_ok=True)
    duplicates = duplicates_by_original(connection)
    pages = {INDEX_PAGE: _index_page(connection, settings), LIBRARY_PAGE: _library_page(connection, settings, duplicates)}
    for project in connection.execute("SELECT * FROM projects ORDER BY name").fetchall():
        pages[project["name"]] = _project_page(connection, settings, project, duplicates)
    for name, lines in pages.items():
        path = directory / f"{name}.md"
        if path.exists() and not _is_generated(path):
            print(f"Render: skipped {path}, a file not written by this tool already has that name")
            continue
        path.write_text("\n".join(lines).rstrip() + "\n")
    for path in directory.glob("*.md"):
        if path.stem not in pages and _is_generated(path):
            path.unlink()
            print(f"Render: removed {path.name}, no longer generated")
    print(f"Render: {len(pages)} pages in {directory}")
